grant select, insert, update, delete on public.app_users to service_role;
grant select, insert, update, delete on public.lead_assignments to service_role;

grant usage, select on sequence public.admin_search_jobs_id_seq to service_role;
grant usage, select on sequence public.ai_token_ledger_id_seq to service_role;
grant usage, select on sequence public.app_users_id_seq to service_role;
grant usage, select on sequence public.lead_assignments_id_seq to service_role;

