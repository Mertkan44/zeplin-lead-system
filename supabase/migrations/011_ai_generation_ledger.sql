-- 011: AI generations tied to their input, one paid call per input, and a
-- per-call usage ledger.
--
-- * ai_generations rows now record what they were generated from
--   (input_hash, prompt_version, catalog_version, requested and actual model)
--   and a status. claim_ai_generation() turns the cache key into a lease, so
--   two requests for the same input make one provider call: the second one
--   gets the finished text, or "busy" while the first is still running.
-- * ai_token_ledger gets one 'usage' row per provider call (including empty
--   responses, failures and fallbacks) and per cache hit, with the token
--   split and the rates applied. A search job's 'reservation' is closed by a
--   'release' row, so open reservations and historical estimates are apart.
-- * ai_model_rates holds provider prices by model and start date. Rows are
--   entered by an admin from the provider's official price list; without a
--   row the code falls back to the DEEPSEEK_*_USD_PER_M_TOKENS settings and
--   records which source it used.
-- * ai_spend_summary() aggregates the whole ledger in the database.
--
-- Additive and idempotent; nothing is removed, so the connector can apply it.

