-- Claim the generation for a cache key. Returns
--   {"status": "ready", "content", "provider", "model"}  finished earlier: use it;
--   {"status": "claimed"}                                 this caller generates;
--   {"status": "busy", "claimed_until"}                   someone else is generating.
-- A failed, expired or empty row is taken over.
create or replace function public.claim_ai_generation(
  p_cache_key text,
  p_task text,
  p_owner text,
  p_lease_seconds integer,
  p_provider text,
  p_requested_model text,
  p_lead_id bigint,
  p_input_hash text,
  p_prompt_version text,
  p_catalog_version text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed_id bigint;
  current_row public.ai_generations;
  lease interval := make_interval(secs => greatest(coalesce(p_lease_seconds, 180), 10));
begin
  insert into public.ai_generations (
    cache_key, task, provider, model, content, status, claimed_by, claimed_until, attempts,
    lead_id, input_hash, prompt_version, catalog_version, requested_model
  ) values (
    p_cache_key, p_task, p_provider, coalesce(p_requested_model, ''), '', 'pending', p_owner, now() + lease, 1,
    p_lead_id, p_input_hash, p_prompt_version, p_catalog_version, p_requested_model
  )
  on conflict (cache_key) do nothing
  returning id into claimed_id;
  if claimed_id is not null then
    return jsonb_build_object('status', 'claimed');
  end if;

  select * into current_row from public.ai_generations where cache_key = p_cache_key for update;
  if current_row.status = 'ready' and coalesce(current_row.content, '') <> '' then
    return jsonb_build_object(
      'status', 'ready', 'content', current_row.content,
      'provider', current_row.provider, 'model', current_row.model
    );
  end if;
  if current_row.status = 'pending'
     and current_row.claimed_until > now()
     and current_row.claimed_by is distinct from p_owner then
    return jsonb_build_object('status', 'busy', 'claimed_until', current_row.claimed_until);
  end if;

  update public.ai_generations
  set status = 'pending',
      claimed_by = p_owner,
      claimed_until = now() + lease,
      attempts = attempts + 1,
      error = null,
      lead_id = coalesce(p_lead_id, lead_id),
      input_hash = p_input_hash,
      prompt_version = p_prompt_version,
      catalog_version = p_catalog_version,
      requested_model = p_requested_model
  where id = current_row.id;
  return jsonb_build_object('status', 'claimed');
end;
$$;

-- Store the finished text. The first completion wins; a later one for an
-- already finished key changes nothing and returns false.
create or replace function public.complete_ai_generation(
  p_cache_key text,
  p_content text,
  p_provider text,
  p_model text,
  p_usage jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.ai_generations
  set status = 'ready', content = p_content, provider = p_provider, model = p_model,
      usage = coalesce(p_usage, '{}'::jsonb), claimed_by = null, claimed_until = null, error = null
  where cache_key = p_cache_key and status <> 'ready';
  return found;
end;
$$;

create or replace function public.fail_ai_generation(p_cache_key text, p_owner text, p_error text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.ai_generations
  set status = 'failed', error = left(p_error, 500), claimed_until = null
  where cache_key = p_cache_key and status = 'pending' and claimed_by = p_owner;
$$;

-- Whole-ledger totals; nothing is capped at the latest N rows.
create or replace function public.ai_spend_summary(p_today_start timestamptz default null)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with usage_rows as (
    select * from public.ai_token_ledger where kind = 'usage'
  ),
  reservations as (
    select job_id,
           sum(estimated_tokens) filter (where kind = 'reservation') as reserved_tokens,
           sum(estimated_cost_usd) filter (where kind = 'reservation') as reserved_usd,
           bool_or(kind = 'release') as released
    from public.ai_token_ledger
    where kind in ('reservation', 'release')
    group by job_id
  )
  select jsonb_build_object(
    'actual_cost_usd', coalesce((select round(sum(actual_cost_usd), 6) from usage_rows), 0),
    'actual_tokens', coalesce((select sum(actual_tokens) from usage_rows), 0),
    'provider_calls', (select count(*) from usage_rows where coalesce(outcome, 'success') <> 'cache_hit'),
    'cache_hits', (select count(*) from usage_rows where outcome = 'cache_hit'),
    'failed_calls', (select count(*) from usage_rows where outcome in ('error', 'empty')),
    'unpriced_calls', (select count(*) from usage_rows where actual_tokens > 0 and actual_cost_usd is null),
    'today_cost_usd', coalesce((
      select round(sum(actual_cost_usd), 6) from usage_rows
      where p_today_start is not null and created_at >= p_today_start
    ), 0),
    'active_reserved_tokens', coalesce((select sum(reserved_tokens) from reservations where not released), 0),
    'active_reserved_usd', coalesce((select round(sum(reserved_usd), 6) from reservations where not released), 0),
    'estimated_cost_usd', coalesce((select round(sum(reserved_usd), 6) from reservations), 0),
    'estimated_tokens', coalesce((select sum(reserved_tokens) from reservations), 0),
    'by_task', coalesce((
      select jsonb_object_agg(task_name, totals) from (
        select coalesce(task, 'unknown') as task_name,
               jsonb_build_object('calls', count(*), 'tokens', coalesce(sum(actual_tokens), 0),
                                  'cost_usd', coalesce(round(sum(actual_cost_usd), 6), 0)) as totals
        from usage_rows where coalesce(outcome, 'success') <> 'cache_hit'
        group by 1
      ) grouped
    ), '{}'::jsonb),
    'by_model', coalesce((
      select jsonb_object_agg(model_name, totals) from (
        select coalesce(model, 'unknown') as model_name,
               jsonb_build_object('calls', count(*), 'tokens', coalesce(sum(actual_tokens), 0),
                                  'cost_usd', coalesce(round(sum(actual_cost_usd), 6), 0)) as totals
        from usage_rows where coalesce(outcome, 'success') <> 'cache_hit'
        group by 1
      ) grouped
    ), '{}'::jsonb)
  );
$$;

