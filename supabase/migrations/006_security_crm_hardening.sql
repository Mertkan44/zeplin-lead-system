create or replace function public.create_admin_search_job(
  query text,
  city text,
  max_results integer,
  deep_research boolean,
  ai_mode text,
  created_by text,
  estimated_tokens integer,
  estimated_cost_usd numeric,
  reservation_meta jsonb default '{}'::jsonb
)
returns setof public.admin_search_jobs
language plpgsql
security definer
set search_path = public
as $$
#variable_conflict use_variable
declare
  created_job public.admin_search_jobs;
begin
  insert into public.admin_search_jobs (
    query, city, max_results, deep_research, ai_mode, created_by,
    estimated_tokens, estimated_cost_usd, meta
  ) values (
    query, city, max_results, deep_research, ai_mode, created_by,
    estimated_tokens, estimated_cost_usd, reservation_meta
  ) returning * into created_job;

  insert into public.ai_token_ledger (
    job_id, kind, provider, model, estimated_tokens, estimated_cost_usd, meta
  ) values (
    created_job.id, 'reservation', 'deepseek',
    reservation_meta->>'model_mix', estimated_tokens, estimated_cost_usd,
    jsonb_build_object('query', query, 'city', city, 'max_results', max_results)
  );

  return next created_job;
end;
$$;

create or replace function public.assign_lead_owner(
  target_lead_name text,
  target_user_email text,
  assignment_due_at timestamptz,
  assignment_by text,
  assignment_status text,
  assignment_meta jsonb default '{}'::jsonb
)
returns setof public.lead_assignments
language plpgsql
security definer
set search_path = public
as $$
declare
  assigned public.lead_assignments;
begin
  if assignment_status = 'active' then
    update public.lead_assignments
    set status = 'archived', updated_at = now()
    where lead_name = target_lead_name
      and status = 'active'
      and user_email <> lower(target_user_email);
  end if;

  insert into public.lead_assignments (
    lead_name, user_email, due_at, assigned_by, status, meta
  ) values (
    target_lead_name, lower(target_user_email), assignment_due_at,
    lower(assignment_by), assignment_status, assignment_meta
  )
  on conflict (lead_name, user_email) do update
  set due_at = excluded.due_at,
      assigned_by = excluded.assigned_by,
      status = excluded.status,
      meta = excluded.meta,
      updated_at = now()
  returning * into assigned;

  return next assigned;
end;
$$;

create or replace function public.claim_admin_search_jobs(job_limit integer default 1)
returns setof public.admin_search_jobs
language plpgsql
security definer
set search_path = public
as $$
begin
  -- A crashed worker may leave a job running. Retry it after one hour.
  update public.admin_search_jobs
  set status = 'queued',
      result = coalesce(result, '{}'::jsonb) || jsonb_build_object('recovered_at', now())
  where status = 'running' and updated_at < now() - interval '1 hour';

  return query
  with candidates as (
    select id
    from public.admin_search_jobs
    where status = 'queued'
    order by created_at asc
    for update skip locked
    limit greatest(1, least(job_limit, 10))
  )
  update public.admin_search_jobs jobs
  set status = 'running',
      result = coalesce(jobs.result, '{}'::jsonb) || jsonb_build_object('started_at', now())
  from candidates
  where jobs.id = candidates.id
  returning jobs.*;
end;
$$;

create or replace function public.check_login_rate_limit(
  attempt_key_hash text,
  attempt_limit integer default 8,
  window_seconds integer default 900
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  recent_attempts integer;
begin
  delete from public.auth_login_attempts
  where attempted_at < now() - interval '1 day';

  select count(*) into recent_attempts
  from public.auth_login_attempts
  where key_hash = attempt_key_hash
    and attempted_at >= now() - make_interval(secs => greatest(60, window_seconds));

  return recent_attempts >= greatest(1, attempt_limit);
end;
$$;

create or replace function public.record_login_attempt(
  attempt_key_hash text,
  attempt_succeeded boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if attempt_succeeded then
    delete from public.auth_login_attempts where key_hash = attempt_key_hash;
  else
    insert into public.auth_login_attempts (key_hash) values (attempt_key_hash);
  end if;
end;
$$;

