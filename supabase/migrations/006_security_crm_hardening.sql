create extension if not exists pgcrypto;

alter table public.leads add column if not exists external_id text;

update public.leads
set external_id = case
  when coalesce(maps_url, raw->>'maps_url', '') <> ''
    then 'maps:' || encode(digest(coalesce(maps_url, raw->>'maps_url'), 'sha256'), 'hex')
  else 'name:' || encode(
    digest(lower(trim(name)) || '|' || lower(trim(coalesce(city, ''))), 'sha256'),
    'hex'
  )
end
where external_id is null;

