-- There can be only one current owner for a lead.
with ranked as (
  select id, row_number() over (
    partition by lead_name
    order by updated_at desc nulls last, id desc
  ) as position
  from public.lead_assignments
  where status = 'active'
)
update public.lead_assignments assignment
set status = 'archived', updated_at = now()
from ranked
where assignment.id = ranked.id and ranked.position > 1;

create unique index if not exists lead_assignments_one_active_owner_uidx
  on public.lead_assignments (lead_name)
  where status = 'active';

